package ru.nstu.poi.model;

import java.util.List;

/**
 * Контракт «сущность можно изменять».
 * Интерфейс несёт метод проверки, а не является маркером: правила корректности
 * живут рядом с данными, и их одинаково используют диалог GUI и сервис.
 */
public interface Editable {

    /** @return список ошибок; пустой список означает, что данные корректны */
    List<String> validate();
}
